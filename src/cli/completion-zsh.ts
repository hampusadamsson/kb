import { allOpts, ACTIONS, ID_COMMANDS, VALUE_KINDS, type Cmd, type Opt } from "./completion-model.js";

const q = (s: string): string => "'" + s.replace(/'/g, "'\\''") + "'";
const colon = (s: string): string => s.replace(/:/g, "\\:");

function action(long: string): string {
  const k = VALUE_KINDS[long] ?? "none";
  if (k === "none") return " ";
  if (k.startsWith("words:")) return `(${k.slice(6)})`;
  if (k === "propkeys") return "_kb_propkeys";
  return `_kb_${k}`;
}

function optSpec(o: Opt): string[] {
  const act = o.takesValue ? `:${o.long.slice(2)}:${action(o.long)}` : "";
  const mk = (f: string): string => q(`${f}[${o.desc.replace(/[[\]]/g, "\\$&")}]${act}`);
  return o.short ? [mk(o.short), mk(o.long)] : [mk(o.long)];
}

/** Zsh completion script, generated from the program. */
export function zsh(global: Opt[], cmds: Cmd[]): string {
  const L: string[] = [];
  L.push("#compdef kb");
  L.push("# zsh completion for kb (generated by `kb completion zsh`)");
  L.push('_kb_dyn() { local -a r; r=(${(f)"$(kb __complete "$@" 2>/dev/null)"}); compadd -a r }');
  L.push("_kb_ids() { local -a r; r=(${(f)\"$(kb __complete ids named 2>/dev/null)\"}); _describe -t ids 'ticket id' r }");
  L.push("_kb_columns() { _kb_dyn columns }");
  L.push("_kb_boards() { _kb_dyn boards }");
  L.push("_kb_labels() { _kb_dyn labels }");
  L.push("_kb_propkeys() { _kb_dyn propkeys }");
  L.push("_kb_rules() { _kb_dyn rules }");
  L.push("_kb() {");
  L.push("  local -a cmds");
  L.push("  cmds=(");
  for (const c of cmds) L.push(`    ${q(`${colon(c.name)}:${c.desc.replace(/'/g, "'\\''")}`)}`);
  L.push("  )");
  L.push("  if (( CURRENT == 2 )); then");
  L.push("    _describe -t commands 'kb command' cmds");
  L.push("    _arguments -s " + global.flatMap(optSpec).join(" "));
  L.push("    return");
  L.push("  fi");
  L.push("  case $words[2] in");
  for (const c of cmds) {
    const specs = allOpts(global, c).flatMap(optSpec);
    const pos: string[] = [];
    if (ID_COMMANDS.includes(c.name)) pos.push("'1:id:_kb_ids'");
    if (c.name === "mv") pos.push("'2:status:_kb_columns_for'");
    if (ACTIONS[c.name]) pos.push(`'1:action:(${ACTIONS[c.name].join(" ")})'`);
    if (c.name === "completion") pos.push("'1:shell:(bash zsh)'");
    L.push(`    ${c.name}) _arguments -s ${[...specs, ...pos].join(" ")} ;;`);
  }
  L.push("  esac");
  L.push("}");
  L.push('_kb_columns_for() { local -a r; r=(${(f)"$(kb __complete columns $words[3] 2>/dev/null)"}); compadd -a r }');
  L.push("compdef _kb kb");
  return L.join("\n") + "\n";
}
