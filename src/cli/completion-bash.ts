import { allOpts, flags, ACTIONS, ID_COMMANDS, kindsOf, type Cmd, type Opt } from "./completion-model.js";

/** Bash completion script, generated from the program. */
export function bash(global: Opt[], cmds: Cmd[]): string {
  const L: string[] = [];
  const cmdNames = [...cmds.map((c) => c.name), "--help", "-h"];
  L.push("# bash completion for kb (generated by `kb completion bash`)");
  L.push('_kb_dyn() { compgen -W "$(kb __complete "$@" 2>/dev/null)" -- "$cur"; }');
  L.push("_kb() {");
  L.push("  local cur prev cmd i pos");
  L.push("  COMPREPLY=()");
  L.push("  cur=${COMP_WORDS[COMP_CWORD]}");
  L.push("  prev=${COMP_WORDS[COMP_CWORD-1]}");
  L.push("  cmd=; pos=0");
  L.push("  for ((i=1; i<COMP_CWORD; i++)); do");
  L.push("    case ${COMP_WORDS[i]} in");
  L.push("      -*) ;;");
  L.push("      *) if [[ -z $cmd ]]; then cmd=${COMP_WORDS[i]}; pos=$i; fi ;;");
  L.push("    esac");
  L.push("  done");
  L.push("  case $prev in");
  for (const [kind, opts] of kindsOf(global, cmds)) {
    const pat = opts.flatMap(flags).join("|");
    if (kind === "none") L.push(`    ${pat}) return 0 ;;`);
    else if (kind.startsWith("words:")) L.push(`    ${pat}) COMPREPLY=($(compgen -W "${kind.slice(6)}" -- "$cur")); return 0 ;;`);
    else if (kind === "columns") L.push(`    ${pat}) COMPREPLY=($(_kb_dyn columns)); return 0 ;;`);
    else L.push(`    ${pat}) COMPREPLY=($(_kb_dyn ${kind})); [[ ${kind} == propkeys ]] && compopt -o nospace 2>/dev/null; return 0 ;;`);
  }
  L.push("  esac");
  L.push("  if [[ -z $cmd ]]; then");
  L.push(`    COMPREPLY=($(compgen -W "${cmdNames.join(" ")}" -- "$cur"))`);
  L.push("    return 0");
  L.push("  fi");
  L.push("  case $cmd in");
  for (const c of cmds) {
    const opts = allOpts(global, c).flatMap(flags).join(" ");
    L.push(`    ${c.name})`);
    if (c.name === "completion")
      L.push('      [[ $((COMP_CWORD - pos)) -eq 1 ]] && { COMPREPLY=($(compgen -W "bash zsh" -- "$cur")); return 0; }');
    if (ACTIONS[c.name])
      L.push(
        `      [[ $((COMP_CWORD - pos)) -eq 1 ]] && { COMPREPLY=($(compgen -W "${ACTIONS[c.name].join(" ")}" -- "$cur")); return 0; }`,
      );
    if (ID_COMMANDS.includes(c.name)) L.push("      [[ $((COMP_CWORD - pos)) -eq 1 ]] && { COMPREPLY=($(_kb_dyn ids)); return 0; }");
    if (c.name === "mv")
      L.push('      [[ $((COMP_CWORD - pos)) -eq 2 ]] && { COMPREPLY=($(_kb_dyn columns "${COMP_WORDS[pos+1]}")); return 0; }');
    L.push(`      [[ $cur == -* ]] && COMPREPLY=($(compgen -W "${opts}" -- "$cur"))`);
    L.push("      ;;");
  }
  L.push("  esac");
  L.push("  return 0");
  L.push("}");
  L.push("complete -F _kb kb");
  return L.join("\n") + "\n";
}
